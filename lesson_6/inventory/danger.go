package inventory

import (
	"errors"
	"fmt"
)

// ErrPanic оборачивает значение, с которым запаниковал код при использовании предмета.
var ErrPanic = errors.New("recovered from panic")

// dangerousItemName — название «специального» предмета, использование которого вызывает панику.
const dangerousItemName = "Бомба"

// UseDangerousItem использует предмет и превращает панику в обычную ошибку.
// Для предмета с названием "Бомба" функция паникует сама; любая другая паника внутри
// Use тоже перехватывается и возвращается как ErrPanic. Обычные проблемы (пустой предмет,
// сломанный предмет) по-прежнему возвращаются как error.
//
// Ответы на вопросы из ТЗ:
//
//  1. Почему ошибка сломанного предмета не должна быть паникой?
//     Сломанный предмет — штатная, ожидаемая ситуация: оружие изнашивается, и вызывающий код
//     умеет с этим жить (errors.Is(err, ErrBroken) и сообщение пользователю). Паника означает,
//     что программа попала в состояние, которого быть не должно (баг, нарушенный инвариант):
//     она раскручивает стек и без recover завершает программу. Ошибка — это значение, которое
//     можно проверить, обернуть и обработать, а паника ломает обычный поток управления.
//  2. Какая строка после panic не будет выполнена?
//     Строка `return item.Use()` ниже. После panic функция не продолжается: выполняются только
//     отложенные вызовы (defer), а затем стек раскручивается дальше.
//  3. Почему recover должен находиться в отложенной функции?
//     Пока идёт паника, обычный код не выполняется, работают только отложенные функции.
//     recover останавливает панику, только если вызван прямо из отложенной функции; вызванный
//     в обычном коде он вернёт nil и ничего не остановит.
func UseDangerousItem(item Item) (message string, err error) {
	defer func() {
		if r := recover(); r != nil {
			message = ""
			err = fmt.Errorf("%w: %v", ErrPanic, r)
		}
	}()

	if isNilItem(item) {
		return "", ErrNilItem
	}

	if item.Name() == dangerousItemName {
		panic("взрыв!")
	}

	return item.Use() // эта строка после panic не выполнится
}
