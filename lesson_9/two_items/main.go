package main

import "fmt"

// TwoItems ищет два РАЗНЫХ товара, сумма цен которых ровно k.
// Возвращает их позиции (с 0) в порядке возрастания и true.
// Если пары нет, возвращает (0, 0, false).
//
// Идея: для цены p нужна цена need = k - p, которую мы должны были
// встретить раньше. Поэтому по ходу запоминаем увиденные цены
// в словаре seen: цена -> позиция.
//
// Время: O(n), память: O(n).
// Наивное решение «каждый с каждым» работало бы за O(n²).
//
// Две ловушки из занятия:
//  1. Сначала проверяем seen, и только потом запоминаем текущую цену.
//     Иначе при k = 1400 и ценах [700, 500] получили бы 700 + 700,
//     то есть один и тот же товар дважды.
//  2. Наличие ключа проверяем через j, ok := seen[need], а не через
//     seen[need] != 0: позиция 0 - честный ответ.
func TwoItems(prices []int, k int) (int, int, bool) {
	seen := make(map[int]int) // цена -> позиция

	for i, p := range prices {
		need := k - p
		if j, ok := seen[need]; ok {
			return j, i, true
		}
		seen[p] = i
	}

	return 0, 0, false
}

func main() {
	fmt.Println(TwoItems([]int{700, 1500, 300, 1200}, 1500)) // 2 3 true
	fmt.Println(TwoItems([]int{700, 800}, 1500))             // 0 1 true
	fmt.Println(TwoItems([]int{700, 500}, 1400))             // 0 0 false
}
